"""Книжные магазины предлагают следующие коллекции книг.
Магистр – Лермонтов, Достоевский, Пушкин, Тютчев
ДомКниги – Толстой, Грибоедов, Чехов, Пушкин.
БукМаркет – Пушкин, Достоевский, Маяковский.
Галерея – Чехов, Тютчев, Пушкин.
Определить:
1.в каких магазинах можно одновременно приобрести книги Достоевского и Пушкина.
2.в ассортимент магазина ДомКниги добавить автора Лермонтов.
3.какие книги из магазина БукМаркет отсутствуют в магазине Магистр."""
magistr = {"Лермонтов", "Достоевский", "Пушкин", "Тютчев"}
dom_knigi = {"Толстой", "Грибоедов", "Чехов", "Пушкин"}
buk_market = {"Пушкин", "Достоевский", "Маяковский"}
galereya = {"Чехов", "Тютчев", "Пушкин"}
try:
    print("1. Магазины с книгами Достоевского и Пушкина:")
    if "Достоевский" in magistr and "Пушкин" in magistr:
        print("- Магистр")
    if "Достоевский" in dom_knigi and "Пушкин" in dom_knigi:
        print("- ДомКниги")
    if "Достоевский" in buk_market and "Пушкин" in buk_market:
        print("- БукМаркет")
    if "Достоевский" in galereya and "Пушкин" in galereya:
        print("- Галерея")
    print()

    print("2. Обновлённый ассортимент магазина ДомКниги:")
    dom_knigi.add("Лермонтов")
    print(f"ДомКниги – {dom_knigi}")
    print()

    print("3. Книги из БукМаркет, отсутствующие в Магистр:")
    if "Пушкин" not in magistr:
        print("- Пушкин")
    if "Достоевский" not in magistr:
        print("- Достоевский")
    if "Маяковский" not in magistr:
        print("- Маяковский")

except Exception as e:
    print(f"Неожиданная ошибка: {e}")