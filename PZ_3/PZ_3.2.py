#Дан номер года (положительное целое число). Определить количество дней в этом,году, учитывая, что обычный год насчитывает 365 дней, а високосный — 366 дней.Високосным считается год, делящийся на 4, за исключением тех годов, которы,еделятся на 100 и не делятся на 400 (например, годы 300, 1300 и 1900 не являются,високосными, а 1200 и 2000 — являются).
def is_leap_year(year):
    #Проверяет, является ли год високосным
    return (year % 4 == 0) and (year % 100 != 0 or year % 400 == 0)
def get_days_in_year(year):
    #Возвращает количество дней в году
    return 366 if is_leap_year(year) else 365
year = int(input("Введите год: "))
if year <= 0:
    print("Год должен быть положительным числом!")
else:
    days = get_days_in_year(year)
    leap_status = "високосный" if is_leap_year(year) else "обычный"
    print(f"В году {year} - {days} дней ({leap_status})")
