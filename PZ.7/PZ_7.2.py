#Дана строка-предложение на русском языке. Вывести самое длинное слово в предложении. Если таких слов несколько, то вывести первое из них. Словом считать набор символов, не содержащий пробелов, знаков препинания и ограниченный пробелами, знаками препинания или началом/концом строки
def самое_длинное_слово(предложение):
    знаки = ".,!?;:-()\"'"
    for знак in знаки:
        предложение = предложение.replace(знак, ' ')
    слова = предложение.split()

    if слова:
        return max(слова, key=len)
    else:
        return None
try:
    текст = input("Введите предложение: ")

    результат = самое_длинное_слово(текст)
    if результат:
        print(f"Самое длинное слово: '{результат}'")
    else:
        print("В предложении нет слов")
except:
    print("Не удалось обработать ввод")